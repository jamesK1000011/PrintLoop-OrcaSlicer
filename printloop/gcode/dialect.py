"""G-code tag dialects (data/dialects.json): bbl and prusa.

detect(text) gives the dialect of a file from its comment tags. feature(name)
gives the canonical OrcaSlicer feature name for a name of either dialect.
"""
import re

from .. import seeds

BBL, PRUSA = "bbl", "prusa"


def table():
    return seeds.load("dialects")


def detect(text, head=400000):
    """bbl, prusa, or None. Reads the first head characters only."""
    part = text[:head]
    score = {}
    for name, d in table()["dialects"].items():
        score[name] = sum(1 for pat in d["detect"] if re.search(pat, part, re.M))
    best = max(score, key=score.get)
    if score[best] == 0:
        return None
    return best


def tags(dialect):
    return {k: re.compile(v) for k, v in table()["dialects"][dialect]["tags"].items()}


_CANON = None


def feature(name):
    global _CANON
    if _CANON is None:
        _CANON = {}
        for canon, names in table()["features"]["canonical"].items():
            for n in names:
                _CANON[n.lower()] = canon
    if name is None:
        return "?"
    return _CANON.get(name.strip().lower(), name.strip())


def orca_version(text, head=4000):
    m = re.search(r";\s*generated by\s+(?:OrcaSlicer|Orca Slicer)\s+([\w.\-]+)", text[:head], re.I)
    if m:
        return m.group(1)
    m = re.search(r";\s*BambuStudio\s+([\w.\-]+)", text[:head])
    return m.group(1) if m else None
